// Должности команды в порядке иерархии: корень дерева сверху, ветви снизу.
export const ROLES = ['Командир', 'Замполит', 'Командир отряда', 'Солдат'];

// Индекс должности в иерархии (для сортировки). Неизвестные роли — в конец.
export function roleRank(role) {
  const i = ROLES.indexOf(role);
  return i === -1 ? ROLES.length : i;
}
